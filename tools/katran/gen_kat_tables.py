#!/usr/bin/env python3
"""Generate and check Core/DSP/Instruments/Katran/KatranTables.c (S103 P1).

What:       writes the seven 128-entry laws and the two scalars of
            KatranTables.h from their formulas (fs = 44,108.07291666667 Hz,
            32-sample blocks); --check compares the committed file byte for
            byte.
Why:        the tables are the by-ear laws; the host model (modules/katran.c)
            and the firmware read the same file, and a hand edit cannot drift.
Accessors:  python3 tools/katran/gen_kat_tables.py [--check];
            make -C tools/dsp_test katran_tables.
Affiliates: KatranTables.h (the declaration and meaning of every table).
"""
import argparse
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "Core", "DSP", "Instruments", "Katran", "KatranTables.c")

FS = 44108.07291666667      # config.h REAL_FS
BLOCK = 32                  # config.h OUTPUT_DMA_SIZE
ROWS = 128


def f32(x):
    """A C float literal with 9 significant digits."""
    s = f"{x:.9g}"
    if "." not in s and "e" not in s:
        s += ".0"
    return s + "f"


def run_k(r):
    """The run decay: T = 0.25 s x 240^(r/126) for 0..126, on at 127."""
    if r >= 127:
        return 1.0
    t = 0.25 * 240.0 ** (r / 126.0)
    return 10.0 ** (-3.0 * BLOCK / (FS * t))


def ce_blocks(r):
    """A chaos envelope's cycle in blocks: 10 ms .. 60 s, log."""
    t = 0.01 * 6000.0 ** (r / 127.0)
    return max(2, int(round(t * FS / BLOCK)))


def time_samples(r):
    """The delay time in samples: 32 x 56^(r/127)."""
    return 32.0 * 56.0 ** (r / 127.0)


def low_cut_k(r):
    """F2's one-pole coefficient, 5 .. 600 Hz log."""
    f = 5.0 * 120.0 ** (r / 127.0)
    return 1.0 - math.exp(-2.0 * math.pi * f / FS)


def plfo_hz(r):
    """The patch LFO rate, 0.02 .. 20 Hz log."""
    return 0.02 * 1000.0 ** (r / 127.0)


def damp_k(r):
    """The arena damping one-pole: open at 0, 300 Hz at 127 log."""
    if r == 0:
        return 1.0
    f = 20.0 * 15.0 ** ((r - 1) / 126.0)
    return 1.0 - math.exp(-2.0 * math.pi * f / FS)


def drive_gain(r):
    """TORCIDO drive: 2^(5 r/127) (x1 .. x32)."""
    return 2.0 ** (5.0 * r / 127.0)


KICK_K = 10.0 ** (-3.0 * BLOCK / (FS * 0.080))
FADE_K = 10.0 ** (-3.0 * BLOCK / (FS * 0.020))


def rows(values, per=4):
    out = []
    for i in range(0, len(values), per):
        out.append("    " + ", ".join(values[i:i + per]) + ",")
    return out


def text():
    L = ["/*",
         " * KatranTables.c - generated by tools/katran/gen_kat_tables.py",
         " * (S103 P1). Do not edit: change the script and run it again.",
         " * Contract and meaning of every table: KatranTables.h.",
         " */",
         '#include "KatranTables.h"',
         "",
         "const float katRunK[KAT_TABLE_ROWS] = {"]
    L += rows([f32(run_k(r)) for r in range(ROWS)])
    L += ["};", "", "const uint32_t katCeBlocks[KAT_TABLE_ROWS] = {"]
    L += rows([str(ce_blocks(r)) + "u" for r in range(ROWS)])
    L += ["};", "", "const float katTimeSamples[KAT_TABLE_ROWS] = {"]
    L += rows([f32(time_samples(r)) for r in range(ROWS)])
    L += ["};", "", "const float katLowCutK[KAT_TABLE_ROWS] = {"]
    L += rows([f32(low_cut_k(r)) for r in range(ROWS)])
    L += ["};", "", "const float katPlfoHz[KAT_TABLE_ROWS] = {"]
    L += rows([f32(plfo_hz(r)) for r in range(ROWS)])
    L += ["};", "", "const float katDampK[KAT_TABLE_ROWS] = {"]
    L += rows([f32(damp_k(r)) for r in range(ROWS)])
    L += ["};", "", "const float katDriveGain[KAT_TABLE_ROWS] = {"]
    L += rows([f32(drive_gain(r)) for r in range(ROWS)])
    L += ["};", "", "const float katKickK = " + f32(KICK_K) + ";",
          "const float katFadeK = " + f32(FADE_K) + ";", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    want = text()
    if a.check:
        have = open(OUT, newline="").read() if os.path.exists(OUT) else None
        if have != want:
            sys.exit(f"gen_kat_tables: {OUT} differs (rerun without --check)")
        print("gen_kat_tables: KatranTables.c matches")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as fh:
        fh.write(want)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
