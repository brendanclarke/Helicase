/*
 * Generate and program the stock-wave block (S084 VX2 VX2-4.3).
 *
 * What:       for each of the 5 waves and 11 levels, computes every point
 *             additively from StockWaveRecipes.c, two points at a time, and
 *             programs each 32-bit word as soon as it is computed (no
 *             scratch RAM).
 * Why:        W4: oversampled-octave layout, 12,224 B per wave, generated
 *             at Load:[Samples] (plan §4.1.2).
 * Inputs:     base (SAMPLE_STOCK_START_ADDRESS); erased flash.
 * Outputs:    61,120 B programmed; 0 ok, else the sampleFlash status.
 * Accessors:  sampleInstall_writeStockBlock().
 * Affiliates: StockWaves.c (the same level offsets), sampleFlash.c,
 *             tools/gen_stock_recipes.py (the same arithmetic, emulated).
 */
#ifndef STOCKWAVEGEN_H_
#define STOCKWAVEGEN_H_

#include <stdint.h>

/* Generated by tools/gen_stock_recipes.py; never edited by hand. */
extern const int16_t stockWaveRecipeA[5][511];
extern const int16_t stockWaveRecipeB[5][511];
extern const float   stockWaveLevelScale[5][11];

/*
 * Program the whole stock block (S084 VX2 VX2-4.3).
 *
 * What:       point m of a level with length L and h harmonics is
 *             sum_k A_q[k]*cos(t) + B_q[k]*sin(t), t = (k*m*4096/L) & 4095
 *             into sine_table; cos = -sine_table[t], sin =
 *             sine_table[(t + 1024) & 4095] (the firmware table stores a
 *             negative cosine). x = sum * levelScale, rounded and saturated
 *             to int16.
 * Why:        the recipes are about 10 KB of flash instead of the 61 KB of
 *             generated tables; generation is modal with audio suspended.
 * Inputs:     base address of the erased stock block.
 * Outputs:    61,120 B programmed; 0 or the sampleFlash status.
 * Accessors:  sampleInstall_writeStockBlock().
 * Affiliates: StockWaveRecipes.c, sine_table, sampleFlash_writeWord().
 */
int stockWaveGen_programAll(uint32_t base);

#endif /* STOCKWAVEGEN_H_ */
